#!/usr/bin/env bash
# Start the experiment-loop driver detached, so it survives a closed terminal or a dropped
# SSH connection. Uses tmux when present, then screen, then nohup.
#
#   launch.sh <project>/.autoresearch/<name>
#
# Run it from the shell whose environment the experiment needs (conda env, CUDA_VISIBLE_DEVICES,
# API keys): that environment is handed to the detached session.
set -euo pipefail

[ $# -eq 1 ] || { echo "usage: $0 <project>/.autoresearch/<name>" >&2; exit 1; }
EXP="$(cd "$1" && pwd)"
[ -f "$EXP/experiment.json" ] || { echo "no experiment.json in $EXP" >&2; exit 1; }
[ -f "$EXP/state.json" ] || { echo "not initialised: run driver.py init and baseline first" >&2; exit 1; }
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$EXP/../.." && pwd)"
PY="${PYTHON:-python3}"
NAME="ar-$(printf %s "$(basename "$EXP")" | tr -c 'A-Za-z0-9_-' '_')"
q() { printf %q "$1"; }

# A tmux server keeps the environment it was started with, so pass the current one explicitly.
# The file can hold secrets: it is private and the runner deletes it as soon as it is loaded.
ENVFILE="$EXP/.launch.env"
( umask 077; export -p > "$ENVFILE" )

RUNNER="$EXP/run_driver.sh"
cat > "$RUNNER" <<EOF
#!/usr/bin/env bash
# generated by launch.sh; re-run launch.sh rather than editing this
if [ -f $(q "$ENVFILE") ]; then source $(q "$ENVFILE"); rm -f $(q "$ENVFILE"); fi
cd $(q "$ROOT")
$(q "$PY") $(q "$HERE/driver.py") run $(q "$EXP") 2>&1 | tee -a $(q "$EXP/driver.log")
EOF
chmod +x "$RUNNER"
STATUS="$(q "$PY") $(q "$HERE/driver.py") status $(q "$EXP")"

if command -v tmux >/dev/null 2>&1; then
  if tmux has-session -t "=$NAME" 2>/dev/null; then
    echo "tmux session $NAME already exists (tmux attach -t $NAME)" >&2; exit 1
  fi
  tmux new-session -d -s "$NAME" -n driver "bash $(q "$RUNNER"); echo '[driver exited]'; exec bash"
  tmux new-window -d -t "$NAME" -n status "while true; do clear; $STATUS; sleep 30; done"
  tmux new-window -d -t "$NAME" -n runlog "tail -F $(q "$EXP/current_run.log")"
  echo "started in tmux session $NAME"
  echo "  watch : tmux attach -t $NAME     (windows: driver, status, runlog; detach with Ctrl-b d)"
elif command -v screen >/dev/null 2>&1; then
  screen -dmS "$NAME" bash "$RUNNER"
  echo "started in screen session $NAME"
  echo "  watch : screen -r $NAME          (detach with Ctrl-a d)"
else
  nohup bash "$RUNNER" >/dev/null 2>&1 &
  echo "started with nohup, pid $!"
  echo "  watch : tail -f $EXP/driver.log"
fi
echo "  status: $STATUS"
echo "  stop  : touch $EXP/STOP           (finishes the current iteration, then writes REPORT.md)"
echo "  resume: run this launcher again; the loop continues from the saved state"
